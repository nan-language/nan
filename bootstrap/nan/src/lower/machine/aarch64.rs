/// The GICv3 the descriptor names: its distributor, and the first CPU's redistributor, each
/// CPU's a stride after the previous one with its frame of software-generated and private
/// interrupts a page after its control frame.
pub(super) const GICD: u64 = 0x0800_0000;
pub(super) const GICR: u64 = 0x080A_0000;
pub(super) const GICR_STRIDE: u64 = 0x2_0000;
const GICR_SGI: u64 = 0x1_0000;

/// The distributor's registers the kernel programs: its control register, set to affinity
/// routing with both groups enabled; its group, set-enable and clear-enable registers, whose
/// word `n` covers interrupts `32n` to `32n + 31`, words one to seven the shared peripheral
/// interrupts a vector names; and its routing registers, a doubleword per interrupt.
const GICD_CTLR: u64 = 0x0;
const GICD_ARE_GROUPS: u64 = (1 << 4) | 0x3;
const GICD_IGROUPR: u64 = 0x080;
const GICD_ISENABLER: u64 = 0x100;
const GICD_ICENABLER: u64 = 0x180;
const GICD_IROUTER: u64 = 0x6000;
const GICD_SPI_WORDS: u64 = 8;

/// The redistributor's wake register with its processor-asleep and children-asleep bits, and the
/// group and set-enable registers of its software-generated and private interrupts.
const GICR_WAKER: u64 = 0x14;
const GICR_WAKER_ASLEEP: u64 = 1 << 1;
const GICR_WAKER_CHILDREN: u64 = 1 << 2;
const GICR_IGROUPR0: u64 = 0x80;
const GICR_ISENABLER0: u64 = 0x100;

/// The software-generated interrupt a halting CPU stops the others with, alone in group 0, which
/// the interrupt controller delivers as a fast interrupt; and the `ICC_SGI0R_EL1` value sending
/// it to every CPU but the writer, its routing-mode bit selecting all other CPUs.
const STOP_INTID: u64 = 0;
const STOP_SGI: u64 = (1 << 40) | (STOP_INTID << 24);

/// The software-generated interrupt the `SendSignal` stub sends, which the dispatcher receives
/// as the CPU signal's vector.
const SIGNAL_INTID: i64 = 1;

/// The system-register encodings the `ReadSysReg` and `WriteSysReg` stubs hold to reach the GIC
/// CPU interface, the vector base, the virtual timer and the virtual counter, as the `mrs` and
/// `msr` instructions encode them.
const ICC_SRE_EL1: u16 = 0x4665;
const ICC_PMR_EL1: u16 = 0x4230;
const ICC_IGRPEN0_EL1: u16 = 0x4666;
const ICC_IGRPEN1_EL1: u16 = 0x4667;
const ICC_IAR1_EL1: u16 = 0x4660;
const ICC_IAR0_EL1: u16 = 0x4640;
const ICC_EOIR1_EL1: u16 = 0x4661;
const ICC_EOIR0_EL1: u16 = 0x4641;
const ICC_SGI0R_EL1: u16 = 0x465F;
const VBAR_EL1: u16 = 0x4600;
const CNTV_TVAL_EL0: u16 = 0x5F18;
const CNTV_CTL_EL0: u16 = 0x5F19;
pub(super) const CNTFRQ_EL0: u16 = 0x5F00;
pub(super) const CNTVCT_EL0: u16 = 0x5F02;

impl Lowering<'_, '_> {
    /// Reads a GIC CPU-interface, vector-base, timer or counter system register through the
    /// `ReadSysReg` stub.
    pub(super) fn read_sysreg(&mut self, fx: &mut Fx, register: u16) -> Value {
        self.call_stub(fx, Stub::ReadSysReg(register), &[])[0]
    }

    /// Writes one through the `WriteSysReg` stub.
    fn write_sysreg(&mut self, fx: &mut Fx, register: u16, value: Value) {
        self.call_stub(fx, Stub::WriteSysReg(register), &[value]);
    }

    /// Sets up the GICv3 for a kernel's executor and gives the glue each CPU runs to take
    /// interrupts. The distributor routes with affinity, puts every shared peripheral interrupt
    /// in group 1 and enables each that a contribution binds, routed to the boot CPU, and the
    /// ITS is set up; the glue enables the private interrupts on each CPU.
    pub fn aarch64_interrupt_setup(&mut self, fx: &mut Fx) -> FuncId {
        let ctlr = fx.ptr(GICD + GICD_CTLR);
        let groups = fx.ptr(GICD_ARE_GROUPS);
        self.mmio_write(fx, 4, ctlr, groups);
        let ones = fx.ptr(0xFFFF_FFFF);
        for word in 1..GICD_SPI_WORDS {
            let group = fx.ptr(GICD + GICD_IGROUPR + 4 * word);
            self.mmio_write(fx, 4, group, ones);
        }
        let bound = self.bound_vectors();
        let mut private = 0;
        for entry in &bound {
            match entry.vector {
                16..32 => private |= 1 << entry.vector,
                SIGNAL_VECTOR => {}
                32.. => {
                    let vector = fx.ptr(entry.vector as u64);
                    let boot = fx.ptr(0);
                    self.aarch64_route(fx, vector, boot);
                }
                _ => {}
            }
        }
        self.its_setup(fx);
        let dispatch = self.dispatcher(&bound);
        let preempt = self.preempt_glue();
        let vbar = self.aarch64_vector_seam(dispatch, preempt);
        self.aarch64_cpu_prepare(vbar, private)
    }

    /// Enables a shared peripheral interrupt routed to CPU `cpu`, for a contribution's binding or
    /// an installed device.
    pub fn aarch64_route(&mut self, fx: &mut Fx, vector: Value, cpu: Value) {
        let affinity = self.hardware_id(fx, cpu);
        let route = fx.b.ins().ishl_imm_s(vector, 3);
        let route = fx.b.ins().iadd_imm_s(route, (GICD + GICD_IROUTER) as i64);
        self.mmio_write(fx, 8, route, affinity);
        self.gic_spi_bit(fx, GICD_ISENABLER, vector);
    }

    /// Disables a shared peripheral interrupt, once no installed device is left on it.
    pub fn aarch64_disable(&mut self, fx: &mut Fx, vector: Value) {
        self.gic_spi_bit(fx, GICD_ICENABLER, vector);
    }

    /// Writes the bit of a shared peripheral interrupt alone to its word of one of the
    /// distributor's set-enable or clear-enable registers, which leave the other bits as they are.
    fn gic_spi_bit(&mut self, fx: &mut Fx, register: u64, vector: Value) {
        let word = fx.b.ins().ushr_imm_s(vector, 5);
        let word = fx.b.ins().ishl_imm_s(word, 2);
        let at = fx.b.ins().iadd_imm_s(word, (GICD + register) as i64);
        let position = fx.b.ins().band_imm_s(vector, 31);
        let one = fx.ptr(1);
        let bit = fx.b.ins().ishl(one, position);
        self.mmio_write(fx, 4, at, bit);
    }

    /// Emits the vector table and common seam, its symbol aligned so `VBAR_EL1` may name it, with
    /// the common seam's calls relocated to the dispatcher and the preemption glue. Gives the
    /// table's symbol.
    fn aarch64_vector_seam(&mut self, dispatch: FuncId, preempt: FuncId) -> FuncId {
        let seam = self
            .module
            .declare_function(
                "_NSvbar",
                Linkage::Local,
                &Signature::new(super::super::CALL_CONV),
            )
            .expect("the vector table");
        let call = |offset: u32, target: FuncId| ModuleReloc {
            offset,
            kind: Reloc::Arm64Call,
            name: target.into(),
            addend: 0,
        };
        let relocs = [call(SEAM_DISPATCH, dispatch), call(SEAM_PREEMPT, preempt)];
        self.module
            .define_function_bytes(seam, VBAR_BYTES, VBAR_SEAM, &relocs)
            .expect("the vector table");
        seam
    }

    /// The glue each CPU runs to take interrupts: it draws its interrupt stack, makes it the
    /// stack exceptions switch to while its own code continues on `SP_EL0`, and loads the vector
    /// table into `VBAR_EL1`. It then wakes its redistributor, puts the stop interrupt in group 0
    /// and its other software-generated and private interrupts in group 1, enables the stop
    /// interrupt, the CPU signal's, the timer's and the private interrupts in `private`, enables
    /// its LPIs when the ITS is set up, enables its GIC CPU interface at the lowest priority,
    /// unmasks fast interrupts, and starts and enables its virtual timer.
    /// Maskable interrupts stay disabled until the executor enables them.
    fn aarch64_cpu_prepare(&mut self, vbar: FuncId, private: u64) -> FuncId {
        let signature = Signature::new(super::super::CALL_CONV);
        let id = self
            .module
            .declare_function("_NScpu_prepare", Linkage::Local, &signature)
            .expect("the CPU preparation glue");
        let sizes = self.interrupt_stack_sizes();
        self.define(id, signature, super::super::lines::HIDDEN, |lo, fx| {
            fx.entry();
            let sizes = lo.data_address(fx, sizes);
            let size = fx.load(PTR, sizes, 0);
            let stack = lo.interrupt_stack(fx, size);
            let top = fx.b.ins().iadd(stack, size);
            lo.call_stub(fx, Stub::InterruptStack, &[top]);
            let table = lo.func_ref(fx, vbar);
            let table = fx.b.ins().func_addr(PTR, table);
            lo.write_sysreg(fx, VBAR_EL1, table);
            let index = lo.running_index(fx);
            let stride = fx.b.ins().imul_imm_s(index, GICR_STRIDE as i64);
            let base = fx.b.ins().iadd_imm_s(stride, GICR as i64);
            let sgi = fx.b.ins().iadd_imm_s(base, GICR_SGI as i64);
            let waker = fx.b.ins().iadd_imm_s(base, GICR_WAKER as i64);
            let state = lo.mmio_read(fx, 4, waker);
            let awake = fx.b.ins().band_imm_s(state, !(GICR_WAKER_ASLEEP as i64));
            lo.mmio_write(fx, 4, waker, awake);
            fx.repeat(&[], |fx, _| {
                let state = lo.mmio_read(fx, 4, waker);
                let children = fx.b.ins().band_imm_s(state, GICR_WAKER_CHILDREN as i64);
                let asleep = fx.b.ins().icmp_imm_s(IntCC::NotEqual, children, 0);
                fx.when(asleep, |fx| {
                    lo.call_stub(fx, Stub::Pause, &[]);
                });
                (asleep, Vec::new())
            });
            let group = fx.b.ins().iadd_imm_s(sgi, GICR_IGROUPR0 as i64);
            let ones = fx.ptr(0xFFFF_FFFF & !(1 << STOP_INTID));
            lo.mmio_write(fx, 4, group, ones);
            let enable = fx.b.ins().iadd_imm_s(sgi, GICR_ISENABLER0 as i64);
            let bits =
                fx.ptr((1 << STOP_INTID) | (1 << SIGNAL_INTID) | (1 << TIMER_INTID) | private);
            lo.mmio_write(fx, 4, enable, bits);
            lo.its_cpu(fx, base);
            let sre = lo.read_sysreg(fx, ICC_SRE_EL1);
            let sre = fx.b.ins().bor_imm_s(sre, 1);
            lo.write_sysreg(fx, ICC_SRE_EL1, sre);
            let pmr = fx.ptr(0xFF);
            lo.write_sysreg(fx, ICC_PMR_EL1, pmr);
            let one = fx.ptr(1);
            lo.write_sysreg(fx, ICC_IGRPEN1_EL1, one);
            lo.write_sysreg(fx, ICC_IGRPEN0_EL1, one);
            lo.call_stub(fx, Stub::FiqOn, &[]);
            lo.start_timer(fx);
            let one = fx.ptr(1);
            lo.write_sysreg(fx, CNTV_CTL_EL0, one);
            fx.b.ins().return_(&[]);
        });
        id
    }

    /// The ticks the virtual counter counts in a millisecond.
    pub(super) fn aarch64_timer_rate(&mut self, fx: &mut Fx) -> Value {
        let frequency = self.read_sysreg(fx, CNTFRQ_EL0);
        let thousand = fx.ptr(1_000);
        fx.b.ins().udiv(frequency, thousand)
    }

    /// Sets the virtual timer to fire once `ticks` of the virtual counter have passed.
    pub(super) fn aarch64_set_timer(&mut self, fx: &mut Fx, ticks: Value) {
        self.write_sysreg(fx, CNTV_TVAL_EL0, ticks);
    }

    /// The vector of what the seam took, from the kind of exception it passes: for an IRQ the
    /// interrupt the controller signals, which this acknowledges, an LPI's identifier included,
    /// or the CPU signal's vector for its software-generated interrupt; for a synchronous
    /// exception
    /// the abort vector or the other one as its syndrome's class gives, and the SError vector for
    /// an SError interrupt. A fast interrupt is the stop a halting CPU sends, which stops this
    /// one; a spurious IRQ returns from the dispatcher at once.
    pub(super) fn aarch64_vector(&mut self, fx: &mut Fx, kind: Value, saved: Value) -> Value {
        let fiq = fx.b.ins().icmp_imm_s(IntCC::Equal, kind, KIND_FIQ);
        fx.when(fiq, |fx| {
            let intid = self.read_sysreg(fx, ICC_IAR0_EL1);
            self.write_sysreg(fx, ICC_EOIR0_EL1, intid);
            self.stop_cpu(fx);
        });
        let irq = fx.b.ins().icmp_imm_s(IntCC::Equal, kind, KIND_IRQ);
        fx.choose_in(
            self,
            irq,
            &[PTR],
            |lo, fx| {
                let intid = lo.read_sysreg(fx, ICC_IAR1_EL1);
                let special = fx.b.ins().iadd_imm_s(intid, -SPURIOUS);
                let spurious =
                    fx.b.ins()
                        .icmp_imm_s(IntCC::UnsignedLessThan, special, SPECIAL);
                fx.when(spurious, |fx| {
                    let zero = fx.ptr(0);
                    fx.b.ins().return_(&[zero]);
                });
                let signal = fx.b.ins().icmp_imm_s(IntCC::Equal, intid, SIGNAL_INTID);
                let vector = fx.ptr(SIGNAL_VECTOR as u64);
                vec![fx.b.ins().select(signal, vector, intid)]
            },
            |_, fx| {
                let syndrome = fx.load(PTR, saved, frame::ESR);
                let class = fx.b.ins().ushr_imm_s(syndrome, CLASS_SHIFT);
                let class = fx.b.ins().band_imm_s(class, ABORT_CLASS_BITS);
                let abort = fx.b.ins().icmp_imm_s(IntCC::Equal, class, ABORT_CLASS);
                let aborted = fx.ptr(ABORT_VECTOR as u64);
                let other = fx.ptr(SYNC_VECTOR as u64);
                let synchronous = fx.b.ins().select(abort, aborted, other);
                let serror = fx.b.ins().icmp_imm_s(IntCC::Equal, kind, KIND_SERROR);
                let error = fx.ptr(SERROR_VECTOR as u64);
                vec![fx.b.ins().select(serror, error, synchronous)]
            },
        )[0]
    }

    /// Writes the GIC CPU interface's end-of-interrupt register for the interrupt the running CPU
    /// serves, the CPU signal's being its software-generated interrupt.
    pub fn aarch64_eoi(&mut self, fx: &mut Fx) {
        let record = self.running_cpu(fx);
        let vector = fx.load(PTR, record, cpu::VECTOR);
        let signal = fx.b.ins().icmp_imm_s(IntCC::Equal, vector, SIGNAL_VECTOR);
        let intid = fx.ptr(SIGNAL_INTID as u64);
        let intid = fx.b.ins().select(signal, intid, vector);
        self.write_sysreg(fx, ICC_EOIR1_EL1, intid);
    }

    /// Sends every other CPU the stop interrupt.
    pub(super) fn aarch64_send_stop(&mut self, fx: &mut Fx) {
        let sgi = fx.ptr(STOP_SGI);
        self.write_sysreg(fx, ICC_SGI0R_EL1, sgi);
    }
}
