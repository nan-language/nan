/// The PCID bits of a CR3 value, its no-flush bit, and the PCID bit a user root's translations
/// flip; the ASID bits of a `TTBR0_EL1` value, and the ASID bit a user root's flip.
const PCID_MASK: i64 = 0xFFF;
const NO_FLUSH: i64 = i64::MIN;
const USER_PCID: i64 = 0x800;
const ASID_MASK: i64 = 0xFF << 48;
const USER_ASID: i64 = 0x80 << 48;

/// The model-specific registers enabling `syscall` and giving its segments, its target and
/// the flags it clears, the bit of `EFER` enabling it, the selectors `STAR` holds, and the
/// trap, interrupt, direction, I/O privilege, nested task and alignment check flags.
const EFER: u32 = 0xC000_0080;
const STAR: u32 = 0xC000_0081;
const LSTAR: u32 = 0xC000_0082;
const FMASK: u32 = 0xC000_0084;
const SYSCALL_ENABLE: i64 = 1;
const SYSCALL_SEGMENTS: u64 = (0x10 << 48) | (0x08 << 32);
