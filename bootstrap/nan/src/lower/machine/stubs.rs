/// The compiler stubs. Each takes its integer arguments and gives its integer result in the
/// registers its architecture's convention names, and returns, but `Halt`, which stops the
/// processor with maskable interrupts disabled, and `EnterImage`. A port stub, on x86_64 alone, takes the port
/// and, for `Out`, the value; a memory-mapped stub takes the address and, for a write, the
/// value; `Copy` and `Fill` take the target, the source or byte, and the length, a copy between
/// overlapping ranges running backwards when its target lies above its source. `Thread` reads
/// the first word of the running CPU's record, which the GS base addresses on x86_64 and
/// `TPIDR_EL1` on AArch64; `SetCpu` points that register at a record. `Cli` and `Sti` disable
/// and enable maskable interrupts; `IrqSave` gives their state and disables them, `IrqRestore`
/// restores it. `IdleWait` halts until an interrupt with maskable interrupts enabled.
/// `DisableFloats` makes every floating-point, SSE and SIMD instruction of the running CPU
/// fault, setting `CR0.TS` on x86_64 and clearing `CPACR_EL1.FPEN` on AArch64.
///
/// The x86_64 stubs are `Lidt`, which loads an interrupt descriptor table; `Wrmsr` and `Rdmsr`,
/// which write and read a model-specific register; `ReadCr2`, `ReadCr3` and `WriteCr3`, the
/// control registers; `Invlpg`; `LoadTables`, which loads a CPU's descriptor tables through
/// their pseudo-descriptor; `EnableAvx`, which enables XSAVE and the x87, SSE and AVX state
/// components where the CPU has AVX; `GigabytePages`, which gives 1 when the CPU maps
/// 1 GiB pages and 0 otherwise; and `ReadTsc`, which reads the time-stamp counter once every
/// earlier instruction has completed. `ConstantTime` sets the running CPU's data-independent
/// timing mode when it has one: on x86_64 DOITM, when `IA32_ARCH_CAPABILITIES` enumerates it,
/// and on AArch64 `PSTATE.DIT`, when `ID_AA64PFR0_EL1` does. `CpuFeatures` records in the
/// running CPU's record the features the other x86_64 stubs read, and makes the CPU's index,
/// which it takes, its `TSC_AUX`. `Cpuid` writes the four registers a leaf and subleaf give at an address;
/// `Rdtscp` gives the counter and writes the CPU's index at an address, reading both with
/// maskable interrupts disabled where the CPU lacks `rdtscp`; `Rdrand` and `Rdseed` write a
/// value at an address and give 1, or give 0 when the CPU lacks the instruction or it keeps
/// failing; `MonitorWait` takes a word's address, the value seen there and a hint, and waits
/// until the word may have changed or an interrupt arrives, returning at once where the CPU
/// lacks `monitor` and `mwait` with interrupts breaking the wait; `FlushAll` drops every cached
/// translation; `Invpcid` takes an `invpcid` kind, a PCID and a page, dropping every cached
/// translation instead where the CPU lacks the instruction or has PCIDs disabled; `Shootdown`
/// drops a page's cached translations, or every one for a scope of 1 or with PCIDs enabled;
/// `Cr3Tag` gives the bits a PCID and the no-flush flag add to a root, none with PCIDs
/// disabled; `ReadXcr0` gives `XCR0`, 0 without XSAVE enabled; `WriteXcr0` writes it and gives
/// 1, or gives 0 for a value `xsetbv` would fault on; `EnableProtection` sets the
/// control-register bit of the `hw::Protection` variant at an index and gives 1, or
/// gives 0 where the CPU lacks it; `ClearBuffers` runs `verw`; and `UserOpen` and `UserClose`
/// allow and forbid access to user pages where SMAP is enabled. The AArch64 stubs are
/// `ReadSysReg` and `WriteSysReg`, each naming a system register by its 15-bit encoding, which
/// the instruction holds; `ReadTtbr0` and `WriteTtbr0`, the low translation-table base
/// register, and `WriteTtbr0Tagged`, which writes it without invalidating; `TlbiPage`, which
/// invalidates a page's translations under the current ASID, `TlbiAsid` and `TlbiAsidPage`,
/// which invalidate those of an ASID, `TlbiAll`, every one of the running CPU, and
/// `TlbiBroadcast`, every CPU's translations of a page under every ASID, or all of them for a
/// scope of 1; `CleanCache`, `CleanInvalidateCache` and `InvalidateCache`, which maintain the
/// data cache lines holding a range given by its address and length, and `SyncInstructions`,
/// which makes the instruction cache see the range's data; `WaitEvent`, which takes a word's
/// address and the value seen there and waits for an event unless the word differs;
/// `SendSignal`, which sends software-generated interrupt 1 to the CPU of an affinity;
/// `EnterRoot`, which installs the entry root with the
/// memory attributes and translation control the entry seams program; `EnterImage`, which masks
/// every exception, turns the MMU and caches off, drops the instruction cache and translations
/// and branches to its third argument, keeping its first two in `x0` and `x1`; `InterruptStack`, which
